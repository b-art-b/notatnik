/// `Vec<T>` → `T[]`, `Option<T>` → `T | null`, other names unchanged.
pub(crate) fn ts_name(rust: &str) -> String {
    let r = rust.replace(' ', "");
    if let Some(inner) = r.strip_prefix("Vec<").and_then(|x| x.strip_suffix('>')) {
        return format!("{}[]", ts_name(inner));
    }
    if let Some(inner) = r.strip_prefix("Option<").and_then(|x| x.strip_suffix('>')) {
        return format!("{} | null", ts_name(inner));
    }
    r
}

fn decl<T: TS + 'static>(cfg: &Config) -> String {
    format!("export {}\n", T::decl(cfg))
}

